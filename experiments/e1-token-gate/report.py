"""Turn out/memstat.txt and out/time.* into RESULTS.md (stdout)."""
import glob
import os
import re
import statistics
import sys

out = sys.argv[1]
m = {}
for line in open(os.path.join(out, "memstat.txt")):
    k, v = line.strip().split("=")
    m[k] = int(v)


def timing(which):
    wall, rss, user = [], [], []
    for f in sorted(glob.glob(os.path.join(out, f"time.{which}.*"))):
        t = open(f).read()
        e = re.search(r"Elapsed \(wall clock\) time .*: (?:(\d+):)?(\d+):([\d.]+)", t)
        wall.append(int(e.group(1) or 0) * 3600 + int(e.group(2)) * 60 + float(e.group(3)))
        user.append(float(re.search(r"User time \(seconds\): ([\d.]+)", t).group(1)))
        rss.append(int(re.search(r"Maximum resident set size \(kbytes\): (\d+)", t).group(1)))
    return len(wall), statistics.median(wall), statistics.median(user), statistics.median(rss)


total = m["total_bytes"]
ret = m["retained_token_bytes"]
frac = ret / total
pct = lambda x: f"{100 * x / total:.1f}%"
mib = lambda x: f"{x / 2**20:.2f} MiB"
nb, wb, ub, rb = timing("base")
ni, wi, ui, ri = timing("inst")
verdict = "WORTH BUILDING" if frac >= 0.25 else "DEAD"

print(f"""# E1 token gate: results

Workload: chibicc (90d1f7f) `-cc1` compiling its own pristine `parse.c` to
assembly, cc1 invoked directly. Generated by `run.sh`; raw numbers in
`out/memstat.txt` and `out/time.*`.

## Answer

**Retained-Token bytes / total bytes allocated = {100 * frac:.1f}%** (measured).

Decision rule (plan E1): retained tokens >= 25% of bytes means build
re-lex-from-offset. {100 * frac:.1f}% < 25%, so **token regeneration is {verdict}
on this workload.**

## Bytes allocated by cc1

"Allocated" = sum of requested malloc/calloc sizes plus realloc growth
(max(0, new - old)), over the whole cc1 process, including allocations libc
makes on chibicc's behalf (strdup, open_memstream, stdio).

| Quantity | Bytes | Share of total | Label |
|---|---:|---:|---|
| Total allocated | {total:,} ({mib(total)}) | 100% | measured |
| Token structs, all ({m['kind_token_allocs']:,} x {m['sizeof_token']} B) | {m['kind_token_bytes']:,} | {pct(m['kind_token_bytes'])} | measured |
| Tokens retained by Node/Obj/Type/Member after parse ({m['retained_tokens']:,}) | {ret:,} | {pct(ret)} | measured |
| ...plus their macro `origin` chains ({m['retained_tokens_with_origin']:,}) | {m['retained_token_bytes_with_origin']:,} | {pct(m['retained_token_bytes_with_origin'])} | measured |
| Tokens still live after parse (chibicc never frees) | {m['live_token_bytes_after_parse']:,} | {pct(m['live_token_bytes_after_parse'])} | measured |
| AST Nodes ({m['kind_node_allocs']:,} x {m['sizeof_node']} B) | {m['kind_node_bytes']:,} | {pct(m['kind_node_bytes'])} | measured |
| Types ({m['kind_type_allocs']:,} x {m['sizeof_type']} B) | {m['kind_type_bytes']:,} | {pct(m['kind_type_bytes'])} | measured |
| Objs ({m['kind_obj_allocs']:,} x {m['sizeof_obj']} B) | {m['kind_obj_bytes']:,} | {pct(m['kind_obj_bytes'])} | measured |
| Members | {m['kind_member_bytes']:,} | {pct(m['kind_member_bytes'])} | measured |
| Everything else, untagged (not broken down; e.g. file buffers, hashmaps, strings, hidesets, macros) | {m['kind_other_bytes']:,} | {pct(m['kind_other_bytes'])} | measured |
| Output buffer (open_memstream, final length) | {m['outbuf_len']:,} | {pct(m['outbuf_len'])} | measured |

By phase: startup {m['phase_startup_bytes']:,}; lex+preprocess {m['phase_lex_pp_bytes']:,};
parse {m['phase_parse_bytes']:,}; codegen {m['phase_codegen_bytes']:,}; write {m['phase_write_bytes']:,}
(measured). All Token bytes are allocated before parse() starts.

Heap: freed or shrunk by realloc {m['bytes_freed']:,} B, peak live {m['peak_live_bytes']:,} B ({mib(m['peak_live_bytes'])}) (measured).
Retained tokens are {100 * ret / m['peak_live_bytes']:.1f}% of peak live heap (measured).

## Time and peak RSS (/usr/bin/time -v, median of {nb} runs)

| Binary | Wall s | User s | Peak RSS | Label |
|---|---:|---:|---:|---|
| pristine chibicc | {wb:.2f} | {ub:.2f} | {rb:,} KiB | measured |
| instrumented chibicc | {wi:.2f} | {ui:.2f} | {ri:,} KiB | measured (RSS inflated by the accounting table) |

## Method

- `chibicc-memstat.patch` tags Token allocations (`new_token` in tokenize.c,
  `copy_token` in preprocess.c) plus Node, Type, Obj, Member, sets a phase
  variable in `cc1()`, and calls the walk after `parse()` returns.
- `memstat.c` replaces malloc/calloc/realloc/reallocarray/free (forwarding to
  glibc `__libc_*`) and records each live pointer's size/kind/phase in an
  mmap'd table.
- The walk starts at the global Obj list and follows Obj (tok, ty, params,
  locals, body, va_area, alloca_bottom), every Node pointer field (tok, ty,
  func_ty, child nodes, member, var, ret_buffer, atomic_addr), Type (name,
  name_pos, origin, base, vla_len, vla_size, members, return_ty, params, next)
  and Member (tok, name, ty). Distinct Token addresses found are "retained".
  Tokens held only by the preprocessor's macro table are not counted.
- Sanity: pristine and instrumented compilers produce byte-identical
  `parse.s` (and match the normal driver path); `run.sh` aborts otherwise.
""")
